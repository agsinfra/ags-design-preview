/** Arabic counted nouns: 1, 2, 3–10 and 11+ take different forms. */
function count(n, one, two, few, many) {
  if (n === 1) return one;
  if (n === 2) return two;
  return `${n} ${n >= 3 && n <= 10 ? few : many}`;
}

